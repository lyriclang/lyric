#!/usr/bin/env python3
"""The Unicode tables of the runtime (design/v5/spec/10 B9 S4, C2): read from the checked-in files of
the Unicode Character Database under runtime/third_party/ucd/, written as C into
runtime/src/unicode_tables.h, which runtime/src/unicode.c includes. The version comes from the
head of PropList.txt and goes into std.string's `unicodeVersion` as well.

    python3 tooling/unicode/gen.py           write both
    python3 tooling/unicode/gen.py --check   exit 1 when either differs from what it would write

Three properties, nothing else (S4): the general category (two-stage table: a block number for
every 2^shift code points, each distinct block once — the shift the smallest total), the simple
case mappings (UnicodeData.txt fields 12 and 13, sorted pairs for a binary search), and
White_Space (PropList.txt, ranges). Only the standard library of Python 3 is used."""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
UCD = ROOT / 'runtime' / 'third_party' / 'ucd'
OUT = ROOT / 'runtime' / 'src' / 'unicode_tables.h'
LYRIC = ROOT / 'stdlib5' / 'std' / 'string.lyr'

# The general categories in UAX #44's order; std.core's UnicodeCategory has its variants in this
# order, and the index is what lyr_unicode_category answers.
CATEGORIES = ['Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Mn', 'Mc', 'Me', 'Nd', 'Nl', 'No',
              'Pc', 'Pd', 'Ps', 'Pe', 'Pi', 'Pf', 'Po', 'Sm', 'Sc', 'Sk', 'So',
              'Zs', 'Zl', 'Zp', 'Cc', 'Cf', 'Cs', 'Co', 'Cn']
LIMIT = 0x110000
VERSION_LINE = re.compile(r'^pub let unicodeVersion: string = "[^"]*";$', re.M)


def read_unicode_data():
    category = [CATEGORIES.index('Cn')] * LIMIT
    upper, lower = [], []
    first = None
    for line in (UCD / 'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
        if not line:
            continue
        fields = line.split(';')
        cp, name, cat = int(fields[0], 16), fields[1], CATEGORIES.index(fields[2])
        if name.endswith(', First>'):
            first = cp
            continue
        if name.endswith(', Last>'):
            for c in range(first, cp + 1):
                category[c] = cat
            first = None
            continue
        category[cp] = cat
        if fields[12]:
            upper.append((cp, int(fields[12], 16)))
        if fields[13]:
            lower.append((cp, int(fields[13], 16)))
    return category, upper, lower


def read_white_space():
    text = (UCD / 'PropList.txt').read_text(encoding='utf-8')
    version = re.match(r'# PropList-(\d+\.\d+\.\d+)\.txt', text)
    if not version:
        sys.exit('PropList.txt: no version in its first line')
    ranges = []
    for line in text.splitlines():
        body = line.split('#', 1)[0].strip()
        if not body:
            continue
        span, prop = (part.strip() for part in body.split(';'))
        if prop != 'White_Space':
            continue
        lo, _, hi = span.partition('..')
        ranges.append((int(lo, 16), int(hi or lo, 16)))
    return version.group(1), sorted(ranges)


def two_stage(values):
    best = None
    for shift in range(4, 11):
        size = 1 << shift
        blocks, index = {}, []
        for start in range(0, LIMIT, size):
            block = tuple(values[start:start + size])
            index.append(blocks.setdefault(block, len(blocks)))
        total = len(index) * 2 + len(blocks) * size
        if best is None or total < best[0]:
            best = (total, shift, index, list(blocks))
    return best[1:]


def numbers(values, per_line, width=0):
    items = [f'{v:#0{width}x}' if width else str(v) for v in values]
    return '\n'.join('    ' + ', '.join(items[i:i + per_line]) + ',' for i in range(0, len(items), per_line))


def render(version, category, upper, lower, white):
    shift, index, blocks = two_stage(category)
    flat = [v for block in blocks for v in block]
    def pairs(name, table):
        return (f'static const LyrCaseMap {name}[{len(table)}] = {{\n'
                + '\n'.join('    ' + ' '.join(f'{{{a:#x}, {b:#x}}},' for a, b in table[i:i + 6])
                            for i in range(0, len(table), 6))
                + '\n};\n')
    return (
        f'/* Generated by tooling/unicode/gen.py from runtime/third_party/ucd (Unicode {version}) — do not\n'
        ' * edit; change the files or the generator and run it again. unicode.c includes it, once. */\n'
        '#ifndef LYR_UNICODE_TABLES_H\n#define LYR_UNICODE_TABLES_H\n\n'
        f'#define LYR_UNICODE_VERSION "{version}"\n\n'
        f'/* The general category: the block of code point c is CATEGORY_INDEX[c >> {shift}], its value\n'
        f' * CATEGORY_BLOCKS[block << {shift} | (c & {(1 << shift) - 1:#x})], an index into UAX #44\'s order. */\n'
        f'#define CATEGORY_SHIFT {shift}\n'
        f'static const uint16_t CATEGORY_INDEX[{len(index)}] = {{\n{numbers(index, 20)}\n}};\n'
        f'static const uint8_t CATEGORY_BLOCKS[{len(flat)}] = {{\n{numbers(flat, 32)}\n}};\n\n'
        '/* The simple case mappings, sorted by the code point mapped. */\n'
        'typedef struct LyrCaseMap { uint32_t from, to; } LyrCaseMap;\n'
        + pairs('UPPER', upper) + pairs('LOWER', lower) +
        '\n/* White_Space, as ranges with both ends in. */\n'
        f'static const uint32_t WHITE_SPACE[{len(white)}][2] = {{\n'
        + '\n'.join(f'    {{{lo:#x}, {hi:#x}}},' for lo, hi in white) +
        '\n};\n\n#endif\n')


def main():
    check = sys.argv[1:] == ['--check']
    if sys.argv[1:] not in ([], ['--check']):
        sys.exit(__doc__)
    category, upper, lower = read_unicode_data()
    version, white = read_white_space()
    tables = render(version, category, upper, lower, white)
    lyric = LYRIC.read_text(encoding='utf-8')
    if not VERSION_LINE.search(lyric):
        sys.exit(f'{LYRIC}: no line `pub let unicodeVersion: string = "…";`')
    lyric_new = VERSION_LINE.sub(f'pub let unicodeVersion: string = "{version}";', lyric)
    stale = [p for p, text in ((OUT, tables), (LYRIC, lyric_new))
             if not p.exists() or p.read_text(encoding='utf-8') != text]
    if check:
        for p in stale:
            print(f'{p.relative_to(ROOT)} differs from what tooling/unicode/gen.py writes', file=sys.stderr)
        return 1 if stale else 0
    OUT.write_text(tables, encoding='utf-8', newline='\n')
    LYRIC.write_text(lyric_new, encoding='utf-8', newline='\n')
    print(f'Unicode {version}: {OUT.relative_to(ROOT)} ({len(tables)} bytes), '
          f'{len(upper)} upper and {len(lower)} lower mappings, {len(white)} White_Space ranges')
    return 0


if __name__ == '__main__':
    sys.exit(main())
